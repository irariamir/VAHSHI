def build_weekly_plan(req: PlanRequest) -> str:
    field = req.field if req.field in BASE_PLANS else "تجربی"
    plan = BASE_PLANS[field]

    md = []
    md.append(f"# 📅 برنامه هفتگی پیشنهادی — {field} | {req.daily_hours} ساعت/روز")
    md.append(f"> پایه: {req.grade} | تمرکز ویژه: {', '.join(req.weak_subjects) if req.weak_subjects else 'متعادل'}")
    md.append("")
    md.append("## ⏰ برنامه روزانه (شنبه تا پنج‌شنبه)")
    md.append("")
    md.append("| ساعت | فعالیت | نکته |")
    md.append("|------|--------|------|")
    for time, activity, *rest in plan["دوشنبه_تا_جمعه"]:
        note = rest[0] if rest else ""
        # highlight weak subjects
        if any(w in activity for w in req.weak_subjects):
            activity = f"**{activity} 🔥**"
        md.append(f"| {time} | {activity} | {note} |")

    md.append("")
    md.append("## 📊 تقسیم تست هفتگی (پیشنهاد)")
    if field == "تجربی":
        md.append("| درس | تست آموزشی | تست تسلطی | مرور |")
        md.append("|-----|-----------|-----------|------|")
        md.append("| زیست | 40 | 30 | 20 |")
        md.append("| شیمی | 30 | 30 | 15 |")
        md.append("| فیزیک | 25 | 25 | 10 |")
        md.append("| ریاضی | 25 | 25 | 10 |")
    elif field == "ریاضی":
        md.append("| درس | تست هفتگی |")
        md.append("|-----|-----------|")
        md.append("| ریاضی | 120 |")
        md.append("| فیزیک | 80 |")
        md.append("| شیمی | 60 |")
    else:
        md.append("| درس | تست هفتگی |")
        md.append("|-----|-----------|")
        md.append("| تخصصی‌ها | 40-60 هر درس |")

    md.append("")
    md.append("## 🎯 جمعه — روز آزمون")
    md.append(f"> {plan['جمعه_آزمون']}")
    md.append("- صبح: آزمون کامل زمان‌دار (ساعت 8-12)")
    md.append("- عصر: تحلیل تک‌تک سوال‌ها + دفتر اشتباهات")
    md.append("- شب: استراحت و مرور سبک هفته بعد")

    md.append("")
    md.append("## ⚡ قوانین طلایی")
    md.append("1. **هر روز مرور 15 دقیقه‌ای** قبل خواب — بدون استثنا")
    md.append("2. **دفتر اشتباهات**: هر تست غلط/نزده رو با دلیل بنویس")
    md.append("3. **پومودورو**: اگه تمرکزت کمه 25-5، اگه خوبه 90-15")
    md.append("4. **گوشی**: موقع مطالعه بذار اتاق دیگه — وحشی اینو جدی بگیر")
    md.append("5. **خواب 7 ساعت** — کم‌خوابی = نابودی حافظه")

    md.append("")
    md.append("### اکشن امروز وحشی 👇")
    md.append(f"1. همین امروز 2 تست آموزشی از **{req.weak_subjects[0] if req.weak_subjects else 'ضعیف‌ترین درست'}** بزن")
    md.append("2. دفتر اشتباهات رو بساز (یه دفتر جدا)")
    md.append("3. بهم بگو فردا چند ساعت خوندی تا برنامه رو دقیق‌تر کنم")

    md.append("")
    md.append("> ⚠️ این برنامه پیش‌فرضه وحشی. اگه بهم بگی دقیقا روزی چند ساعت وقت آزاد داری و مدرسه‌ات تا کیه، همین الان شخصی‌سازیش می‌کنم.")

    return "\n".join(md)


