# Prompt for evaluation step
EVALUATION_QUESTIONS = [
    "وحشی رشته‌ات چیه؟ (ریاضی / تجربی / انسانی / هنر / زبان)",
    "پایه‌ات چیه؟ (دهم، یازدهم، دوازدهم، پشت‌کنکوری)",
    "تا کنکور چقدر وقت داری؟ هدفت کنکور 1405 هست یا 1406؟",
    "روزانه الان چند ساعت می‌خونی؟ (صادقانه بگو)",
    "قوی‌ترین و ضعیف‌ترین درسات کدوماست؟",
    "هدفت چیه؟ (رشته/دانشگاه/رتبه مد نظرت)",
    "تا حالا آزمون آزمایشی شرکت کردی؟ ترازت حدودا چنده؟",
]

def get_system_prompt(extra_context: str = "") -> str:
    if extra_context:
        return SYSTEM_PROMPT + "\n\n# اطلاعات اضافه\n" + extra_context
    return SYSTEM_PROMPT

def get_evaluation_prompt() -> str:
    qs = "\n".join([f"{i+1}. {q}" for i, q in enumerate(EVALUATION_QUESTIONS)])
    return f"برای اینکه بتونم دقیق برنامه بدم، وحشی اینا رو بهم بگو:\n\n{qs}\n\n(می‌تونی خلاصه جواب بدی، ولی هرچی دقیق‌تر بگی برنامه‌ات دقیق‌تر میشه)"
